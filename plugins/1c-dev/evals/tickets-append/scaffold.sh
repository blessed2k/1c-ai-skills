# Под заказ: техническая спека

## Задача
Менеджеры хотят видеть, какая номенклатура поставляется только под заказ.

## Решение
Булев реквизит «ПодЗаказ» в справочнике Номенклатура через расширение, флаг на форме элемента,
отбор по флагу в отчёте «Остатки товаров».

## Состав метаданных
| Имя | Синоним | Новый или изменяемый | Что меняется |
|---|---|---|---|
| Справочник.Номенклатура | Номенклатура | изменяемый | реквизит ПодЗаказ (Булево) |
| Отчет.ОстаткиТоваров | Остатки товаров | изменяемый | отбор по ПодЗаказ |

## Движения и данные
Движений нет.

## Точки врезки
Форма элемента: &После ПриСозданииНаСервере. Отчёт: заимствование схемы в расширении.

## Права и видимость
Роль расширения: чтение и изменение реквизита.

## Чем проверяем
YAxUnit на заполнение, ручная проверка под ролью, прогон отчёта.

## Вне рамок
Обмены.
MD
